//! Mechanical Bend rendering. Semantic decisions happen in `ir`.
use crate::ir::{self, Expr, Primitive};
use std::collections::BTreeSet;

const PRELUDE: &str = r#"# Generated by scheme-bend. Do not edit this prelude by hand.
# Lists are immutable. `car`/`cdr` on Nil use a documented total sentinel.
type SchemeList:
  Nil
  Cons { head, tail }

def scheme_car(xs):
  match xs:
    case SchemeList/Cons:
      return xs.head
    case SchemeList/Nil:
      return +0

def scheme_cdr(xs):
  match xs:
    case SchemeList/Cons:
      return xs.tail
    case SchemeList/Nil:
      return SchemeList/Nil

def scheme_null(xs):
  match xs:
    case SchemeList/Nil:
      return 1
    case SchemeList/Cons:
      return 0

"#;

pub fn emit(program: &ir::Program) -> String {
    let globals = program
        .definitions
        .iter()
        .filter(|d| d.params.is_empty())
        .map(|d| d.name.clone())
        .collect::<BTreeSet<_>>();
    let mut out = PRELUDE.to_owned();
    let mut emitter = Emitter::default();
    for definition in &program.definitions {
        let params = definition
            .params
            .iter()
            .map(|p| mangle(p))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("def {}({params}):\n", mangle(&definition.name)));
        emitter.emit_return(&definition.body, 1, &globals, &mut out);
        out.push('\n');
    }
    out.push_str("def main():\n");
    match &program.body {
        Some(body) => emitter.emit_return(body, 1, &globals, &mut out),
        None => out.push_str("  return +0\n"),
    }
    out
}

#[derive(Default)]
struct Emitter {
    next_temp: usize,
}
impl Emitter {
    fn temp(&mut self) -> String {
        let name = format!("scheme_tmp_{}", self.next_temp);
        self.next_temp += 1;
        name
    }
    fn emit_return(
        &mut self,
        expr: &Expr,
        depth: usize,
        globals: &BTreeSet<String>,
        out: &mut String,
    ) {
        let pad = "  ".repeat(depth);
        match expr {
            Expr::Let { bindings, body } => {
                for (name, value) in bindings {
                    let value = self.emit_value(value, depth, globals, out);
                    out.push_str(&format!("{pad}{} = {value}\n", mangle(name)));
                }
                self.emit_return(body, depth, globals, out);
            }
            Expr::If {
                condition,
                then_branch,
                else_branch,
            } => {
                if let Some(name) = zero_test_variable(condition) {
                    self.emit_zero_switch(name, then_branch, else_branch, depth, globals, out);
                } else {
                    let condition = self.emit_value(condition, depth, globals, out);
                    out.push_str(&format!("{pad}if {condition}:\n"));
                    self.emit_return(then_branch, depth + 1, globals, out);
                    out.push_str(&format!("{pad}else:\n"));
                    self.emit_return(else_branch, depth + 1, globals, out);
                }
            }
            _ => {
                let value = self.emit_value(expr, depth, globals, out);
                out.push_str(&format!("{pad}return {value}\n"));
            }
        }
    }
    /// Lower `(if (= x 0) then else)` to a native numeric `switch`.
    ///
    /// Bend's `switch` matches `0` against the first arm and sends everything
    /// else -- including negative I24 values -- to `_`, which is exactly the
    /// comparison's semantics, so this is safe for every input. It saves the
    /// compare interaction, and the `_` arm additionally exposes a free
    /// predecessor binding for the switched variable, which retires the
    /// `(- x 1)` that countdown loops otherwise pay for each iteration.
    fn emit_zero_switch(
        &mut self,
        name: &str,
        then_branch: &Expr,
        else_branch: &Expr,
        depth: usize,
        globals: &BTreeSet<String>,
        out: &mut String,
    ) {
        let pad = "  ".repeat(depth);
        let switched = mangle(name);
        let predecessor = self.temp();
        let (else_body, uses_predecessor) = use_predecessor(else_branch, name, &predecessor);
        out.push_str(&format!("{pad}switch {switched}:\n"));
        out.push_str(&format!("{pad}  case 0:\n"));
        self.emit_return(then_branch, depth + 2, globals, out);
        out.push_str(&format!("{pad}  case _:\n"));
        if uses_predecessor {
            out.push_str(&format!(
                "{0}    {1} = {switched}-1\n",
                pad,
                mangle(&predecessor)
            ));
        }
        self.emit_return(&else_body, depth + 2, globals, out);
    }

    fn emit_value(
        &mut self,
        expr: &Expr,
        depth: usize,
        globals: &BTreeSet<String>,
        out: &mut String,
    ) -> String {
        let pad = "  ".repeat(depth);
        match expr {
            Expr::Number(n) => signed_literal(*n),
            Expr::Bool(true) => "1".into(),
            Expr::Bool(false) => "0".into(),
            Expr::Nil => "SchemeList/Nil".into(),
            Expr::Var(name) if globals.contains(name) => format!("{}()", mangle(name)),
            Expr::Var(name) => mangle(name),
            Expr::Call { callee, args } => {
                let args = args
                    .iter()
                    .map(|arg| self.emit_value(arg, depth, globals, out))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{}({args})", mangle(callee))
            }
            Expr::Primitive { op, args } => {
                let args = args
                    .iter()
                    .map(|arg| self.emit_value(arg, depth, globals, out))
                    .collect::<Vec<_>>();
                render_primitive(*op, &args)
            }
            Expr::Cons(head, tail) => {
                let head = self.emit_value(head, depth, globals, out);
                let tail = self.emit_value(tail, depth, globals, out);
                format!("SchemeList/Cons {{ head: {head}, tail: {tail} }}")
            }
            Expr::Car(value) => {
                let value = self.emit_value(value, depth, globals, out);
                format!("scheme_car({value})")
            }
            Expr::Cdr(value) => {
                let value = self.emit_value(value, depth, globals, out);
                format!("scheme_cdr({value})")
            }
            Expr::Null(value) => {
                let value = self.emit_value(value, depth, globals, out);
                format!("scheme_null({value})")
            }
            Expr::Let { bindings, body } => {
                for (name, value) in bindings {
                    let value = self.emit_value(value, depth, globals, out);
                    out.push_str(&format!("{pad}{} = {value}\n", mangle(name)));
                }
                self.emit_value(body, depth, globals, out)
            }
            Expr::If {
                condition,
                then_branch,
                else_branch,
            } => {
                let condition = self.emit_value(condition, depth, globals, out);
                let result = self.temp();
                out.push_str(&format!("{pad}if {condition}:\n"));
                let then_value = self.emit_value(then_branch, depth + 1, globals, out);
                out.push_str(&format!(
                    "{}{} = {then_value}\n",
                    "  ".repeat(depth + 1),
                    result
                ));
                out.push_str(&format!("{pad}else:\n"));
                let else_value = self.emit_value(else_branch, depth + 1, globals, out);
                out.push_str(&format!(
                    "{}{} = {else_value}\n",
                    "  ".repeat(depth + 1),
                    result
                ));
                result
            }
        }
    }
}
/// Recognizes `(= x 0)` / `(= 0 x)` and returns the compared variable.
fn zero_test_variable(condition: &Expr) -> Option<&str> {
    let Expr::Primitive { op, args } = condition else {
        return None;
    };
    if !matches!(op, Primitive::Eq) {
        return None;
    }
    let [left, right] = args.as_slice() else {
        return None;
    };
    let is_zero = |expr: &Expr| matches!(expr, Expr::Number(0) | Expr::Bool(false));
    match (left, right) {
        (Expr::Var(name), other) if is_zero(other) => Some(name),
        (other, Expr::Var(name)) if is_zero(other) => Some(name),
        _ => None,
    }
}

/// Replaces `(- name 1)` with `predecessor`, reporting whether it matched.
fn use_predecessor(expr: &Expr, name: &str, predecessor: &str) -> (Expr, bool) {
    let replaced = |args: &Vec<Expr>| {
        matches!(
            args.as_slice(),
            [Expr::Var(argument), Expr::Number(1)] if argument == name
        )
    };
    match expr {
        Expr::Primitive { op, args } if matches!(op, Primitive::Sub) && replaced(args) => {
            (Expr::Var(predecessor.to_owned()), true)
        }
        Expr::Primitive { op, args } => {
            let (args, used) = use_predecessor_all(args, name, predecessor);
            (Expr::Primitive { op: *op, args }, used)
        }
        Expr::Call { callee, args } => {
            let (args, used) = use_predecessor_all(args, name, predecessor);
            (
                Expr::Call {
                    callee: callee.clone(),
                    args,
                },
                used,
            )
        }
        Expr::If {
            condition,
            then_branch,
            else_branch,
        } => {
            let (condition, a) = use_predecessor(condition, name, predecessor);
            let (then_branch, b) = use_predecessor(then_branch, name, predecessor);
            let (else_branch, c) = use_predecessor(else_branch, name, predecessor);
            (
                Expr::If {
                    condition: Box::new(condition),
                    then_branch: Box::new(then_branch),
                    else_branch: Box::new(else_branch),
                },
                a || b || c,
            )
        }
        Expr::Let { bindings, body } => {
            let mut used = false;
            let bindings = bindings
                .iter()
                .map(|(binding, value)| {
                    let (value, hit) = use_predecessor(value, name, predecessor);
                    used |= hit;
                    (binding.clone(), value)
                })
                .collect();
            let (body, hit) = use_predecessor(body, name, predecessor);
            (
                Expr::Let {
                    bindings,
                    body: Box::new(body),
                },
                used || hit,
            )
        }
        Expr::Cons(head, tail) => {
            let (head, a) = use_predecessor(head, name, predecessor);
            let (tail, b) = use_predecessor(tail, name, predecessor);
            (Expr::Cons(Box::new(head), Box::new(tail)), a || b)
        }
        Expr::Car(value) => {
            let (value, used) = use_predecessor(value, name, predecessor);
            (Expr::Car(Box::new(value)), used)
        }
        Expr::Cdr(value) => {
            let (value, used) = use_predecessor(value, name, predecessor);
            (Expr::Cdr(Box::new(value)), used)
        }
        Expr::Null(value) => {
            let (value, used) = use_predecessor(value, name, predecessor);
            (Expr::Null(Box::new(value)), used)
        }
        leaf => (leaf.clone(), false),
    }
}

fn use_predecessor_all(args: &[Expr], name: &str, predecessor: &str) -> (Vec<Expr>, bool) {
    let mut used = false;
    let args = args
        .iter()
        .map(|arg| {
            let (arg, hit) = use_predecessor(arg, name, predecessor);
            used |= hit;
            arg
        })
        .collect();
    (args, used)
}

fn signed_literal(n: i64) -> String {
    if n >= 0 {
        format!("+{n}")
    } else {
        n.to_string()
    }
}
fn render_primitive(op: Primitive, args: &[String]) -> String {
    let symbol = match op {
        Primitive::Add => "+",
        Primitive::Sub => "-",
        Primitive::Mul => "*",
        Primitive::Div => "/",
        Primitive::Eq => "==",
        Primitive::Lt => "<",
        Primitive::Gt => ">",
        Primitive::Le => "<=",
        Primitive::Ge => ">=",
    };
    format!("({} {symbol} {})", args[0], args[1])
}
pub fn mangle(name: &str) -> String {
    let mut result = String::from("s_");
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            result.push(ch);
        } else {
            result.push_str(&format!("_{}_,", ch as u32));
        }
    }
    result.replace(',', "")
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn mangles_scheme_punctuation() {
        assert_eq!(mangle("tree-sum?"), "s_tree_45_sum_63_");
    }
    #[test]
    fn emits_signed_i24_literals() {
        assert_eq!(signed_literal(-3), "-3");
        assert_eq!(signed_literal(3), "+3");
    }
}
